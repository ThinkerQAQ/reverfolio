import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const source=readFileSync(new URL("../internal/echo/web/app.js",import.meta.url),"utf8");
const taskCode=source.slice(source.indexOf("function tasksView(){"),source.indexOf("function historyView(){"));
const coverageCode=source.slice(source.indexOf("function discoveryCoveragePanel(){"));
const state={leases:new Map(),data:{works:[{id:1,title:"Example work"}],mentions:[],audit:{search_runs:[]},tasks:[{id:7,work_id:1,state:"running",query:"Exact old name",lease_until:"2000-01-01T00:00:00Z"}],discoveryCoverage:{runs:[{task_id:7,engine:"fixture",scope:"One explicitly checked source",status:"complete",checked_result:"not_found_in_checked_scope",queries:["Exact old name"],mention_ids:[],completed_at:"2026-01-01T00:00:00Z"}],identifiers:[],suggested_queries:{1:['"Old name"']}}}};
const E=x=>String(x??"").replaceAll("<","&lt;").replaceAll('"',"&quot;");
const context={state,E,T:x=>x,settingsLabel:x=>Array.isArray(x)?x[1]:x,heading:(x,y)=>x+(y||""),fmt:String,tag:x=>x,anchor:E,dt:String,input:()=>"",select:()=>"",workSelection:()=>"",Date};
vm.createContext(context);vm.runInContext(taskCode+coverageCode,context);
let html=context.tasksView();
assert.match(html,/Not found in checked scope/);
assert.match(html,/One explicitly checked source/);
assert.match(html,/do not establish global absence/);
let button=html.match(/<button[^>]*data-action="claim"[^>]*>/)[0];
assert.ok(!button.includes("disabled"),"Expired leases must be reclaimable");
state.data.tasks[0].lease_until="2099-01-01T00:00:00Z";
state.leases.set(7,"private-fixture-token");
html=context.tasksView();
button=html.match(/<button[^>]*data-action="claim"[^>]*>/)[0];
assert.ok(button.includes("disabled"),"An active lease cannot be stolen");
assert.match(html,/Renew for ten minutes/);
assert.match(html,/name="queries"/);
assert.match(html,/name="mention_ids"/);
assert.ok(!html.includes("private-fixture-token"),"Lease tokens must stay out of page markup");
console.log("Discovery UI distinguishes checked-scope absence, lease expiry, actual queries and private lease ownership.");
