import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";

const source=readFileSync(new URL("../internal/echo/web/app.js",import.meta.url),"utf8");
assert.match(source, /propagation:propagationView/,"Navigation must register the propagation page");
const first=source.indexOf("function propagationView(){");
const last=source.indexOf("\nfunction evidenceView(){",first);
assert.ok(first>0&&last>first,"Propagation page must have a standalone renderer");
const code=source.slice(first,last);
const article={id:11,kind:"article",title:"Original article",canonical_url:"https://example.org/articles/original/"};
const other={id:12,kind:"article",title:"Unrelated article",canonical_url:"https://example.org/articles/other/"};
const page={work_id:11,platform:"example.org",language:"en",url:"https://example.org/en/articles/original/"};
const syndication={work_id:11,platform:"devto",language:"en",url:"https://dev.to/example/original"};
const mention={id:1,work_id:11,url:"https://reader.example.net/review",type:"citation",actor_name:"Real reviewer",state:"verified",origin:"third_party",event_key:"review-1",verified_at:"2026-11-01T12:00:00Z",discovered_at:"2026-10-31T08:00:00Z",evidence:[{observed_at:"2026-10-30T08:00:00Z"}]};
const pending={...mention,id:3,event_key:"draft",url:"https://not-verified.example.org/",state:"pending"};
const duplicate={...mention,id:2,url:"https://reader.example.net/same-event"};
const state={data:{works:[article,other],channels:new Map([[11,[page,syndication]],[12,[{work_id:12,platform:"example.org",language:"en",url:"https://example.org/en/articles/other/"}]]]),mentions:[mention,duplicate,pending]},propagationWork:null};
const E=x=>String(x??"").replaceAll("&","&amp;").replaceAll("<","&lt;").replaceAll('"',"&quot;");
const context={state,E,settingsLabel:tuple=>tuple[1],heading:(a,b)=>'<h2>'+a+'</h2><p>'+b+'</p>',fmt:x=>String(x),anchor:(url,label)=>'<a href="'+E(url)+'">'+E(label)+'</a>',dt:x=>String(x),URL,Set,Map};
vm.createContext(context);vm.runInContext(code,context);
let html=context.propagationView();
assert.match(html,/Propagation paths/);
assert.match(html,/Canonical work/);
assert.match(html,/First-party language versions/);
assert.match(html,/External distribution URLs/);
assert.match(html,/Verified third-party events/);
assert.match(html,/dev.to\/example\/original/);
assert.match(html,/example.org\/en\/articles\/original/);
assert.match(html,/Third-party evidence timeline/);
assert.match(html,/First observed · 2026-10-30T08:00:00Z/);
assert.match(html,/Verified at · 2026-11-01T12:00:00Z/);
assert.doesNotMatch(html,/not-verified\.example\.org/,"Pending mentions must not be presented as confirmed evidence");
assert.doesNotMatch(html,/same-event/,"One event key must display only once");
assert.match(html,/not a publication chronology/,"Do not fabricate channel publish times");
state.propagationWork="12";
html=context.propagationView();
assert.match(html,/Unrelated article/);
assert.doesNotMatch(html,/dev.to\/example\/original/,"Chosen work must isolate channels");
assert.doesNotMatch(html,/Real reviewer/,"Chosen work must isolate external evidence");
console.log("Propagation paths preserve URL provenance, explicit timestamps, deduplicated verified events and per-work scope.");
