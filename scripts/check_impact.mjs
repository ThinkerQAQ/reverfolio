import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const source=readFileSync(new URL("../internal/echo/web/app.js",import.meta.url),"utf8");
const first=source.indexOf("const impactKinds=");
const last=source.indexOf("async function saveImpactForm",first);
const state={data:{works:[],mentions:[],impactEvents:[{id:1,event_key:"pending",title:"Pending contribution",kind:"upstream_contribution",direction:"outbound",state:"pending",effective_state:"pending",outcome:"not_confirmed"}]}};
const E=x=>String(x??"").replaceAll("<","&lt;").replaceAll('"',"&quot;");
const context={state,E,settingsLabel:x=>Array.isArray(x)?x[1]:x,heading:x=>"<h2>"+x+"</h2>",stat:(a,b)=>a+":"+b,tag:x=>x,anchor:u=>E(u),dt:x=>String(x)};
vm.createContext(context);vm.runInContext(source.slice(first,last),context);
let html=context.impactEventsView();
assert.match(html,/Pending contribution/);
assert.match(html,/Verified independent events:0/);
state.data.mentions=[{id:2,url:"https://example.org/outcome",state:"verified"}];
state.data.impactEvents.push({id:2,event_key:"one-result",title:"One actual result",kind:"adoption",direction:"inbound",state:"verified",effective_state:"verified",outcome:"achieved",work_ids:[],evidence:[{mention_id:2,role:"outcome"}],steps:[{kind:"fixed",label:"Fix verified",mention_id:2}]});
html=context.impactEventsView();
assert.match(html,/Verified independent events:1/);
assert.match(html,/Achieved outcomes:1/);
assert.match(html,/https:\/\/example.org\/outcome/);
assert.match(html,/Time unknown/);
state.data.impactEvents[1].effective_state="needs_review";
html=context.impactEventsView();
assert.match(html,/Verified independent events:0/);
assert.match(html,/Achieved outcomes:0/);
console.log("Impact UI handles pending contributions, optional evidence, original links and retracted outcomes.");
